/**
 * The diversion certificate PDF in Chintan's format (Annex C).
 *
 * Produced in the browser and uploaded to Drive, so the issued certificate and
 * the row in the register always carry the same number.
 */

import { APP } from "../config/appConfig";
import { date as fmtDate, num } from "./format";

export async function buildDiversionPdf({ certificate, bwg, vendorName, signatory, logoUrl }) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "portrait", unit: "pt", format: "a4" });

  const width = doc.internal.pageSize.getWidth();
  const height = doc.internal.pageSize.getHeight();
  const margin = 56;
  const inner = width - margin * 2;

  // ---- border ----
  doc.setDrawColor(27, 107, 79);
  doc.setLineWidth(2);
  doc.rect(margin - 16, margin - 24, inner + 32, height - margin * 2 + 48);
  doc.setLineWidth(0.5);
  doc.setDrawColor(143, 212, 180);
  doc.rect(margin - 11, margin - 19, inner + 22, height - margin * 2 + 38);

  // ---- letterhead ----
  const logo = await loadLogo(logoUrl);
  if (logo) {
    try { doc.addImage(logo, "JPEG", margin, margin - 6, 54, 54); } catch { /* ignore */ }
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(15, 61, 46);
  doc.text(APP.org, logo ? margin + 68 : margin, margin + 14);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(118, 133, 127);
  doc.text("Waste Operations Tracking System", logo ? margin + 68 : margin, margin + 28);

  doc.setDrawColor(227, 232, 230);
  doc.line(margin, margin + 56, width - margin, margin + 56);

  // ---- title ----
  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.setTextColor(15, 61, 46);
  doc.text("CERTIFICATE OF WASTE DIVERSION", width / 2, margin + 96, { align: "center" });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  doc.setTextColor(90, 100, 95);
  doc.text(
    `Certificate No. ${certificate.Diversion_Certificate_No}`,
    width / 2, margin + 116, { align: "center" }
  );
  doc.text(
    `Date of issue: ${fmtDate(certificate.Certificate_Date)}`,
    width / 2, margin + 131, { align: "center" }
  );

  // ---- body ----
  let y = margin + 172;
  doc.setFontSize(10.5);
  doc.setTextColor(40, 55, 48);

  const intro =
    `This is to certify that the waste described below, generated by ` +
    `${bwg?.BWG_Name || certificate.BWG_Code} and collected through ` +
    `${APP.shortOrg}, has been diverted from landfill and processed by an ` +
    `authorised service provider.`;

  for (const line of doc.splitTextToSize(intro, inner)) {
    doc.text(line, margin, y);
    y += 16;
  }

  // ---- details table ----
  y += 16;
  const rows = [
    ["Bulk Waste Generator", `${certificate.BWG_Code} — ${bwg?.BWG_Name || ""}`],
    ["Address", bwg?.Address || "—"],
    ["Area", bwg?.Area || "—"],
    ["Material group", certificate.Material_Group],
    ["Quantity diverted", `${num(certificate.Quantity_Kg, 2)} kg`],
    ["Processing method", certificate.Processing_Method],
    ["Period covered", `${fmtDate(certificate.Period_From)} to ${fmtDate(certificate.Period_To)}`],
    ["Processed by", `${certificate.Vendor_Code} — ${vendorName || ""}`],
    ["Against vendor certificate", certificate.Vendor_Certificate_Number],
  ];

  const labelWidth = 170;
  const rowHeight = 26;

  doc.setDrawColor(227, 232, 230);
  doc.setLineWidth(0.5);

  rows.forEach(([label, value], i) => {
    const top = y + i * rowHeight;

    if (i % 2 === 0) {
      doc.setFillColor(248, 251, 250);
      doc.rect(margin, top, inner, rowHeight, "F");
    }
    doc.rect(margin, top, inner, rowHeight);
    doc.line(margin + labelWidth, top, margin + labelWidth, top + rowHeight);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(90, 100, 95);
    doc.text(label, margin + 10, top + 17);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9.5);
    doc.setTextColor(17, 38, 31);
    const text = doc.splitTextToSize(String(value || "—"), inner - labelWidth - 20)[0];
    doc.text(text, margin + labelWidth + 10, top + 17);
  });

  y += rows.length * rowHeight + 30;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(118, 133, 127);
  const note =
    "This certificate is issued on the basis of the processing certificate received from " +
    "the service provider named above, and covers only the quantity stated.";
  for (const line of doc.splitTextToSize(note, inner)) {
    doc.text(line, margin, y);
    y += 13;
  }

  // ---- signature and stamp ----
  const blockTop = Math.max(y + 48, height - margin - 150);

  doc.setDrawColor(150, 160, 155);
  doc.line(margin, blockTop + 46, margin + 190, blockTop + 46);

  doc.setFontSize(9);
  doc.setTextColor(40, 55, 48);
  if (signatory?.name) doc.text(signatory.name, margin, blockTop + 60);
  doc.setFontSize(8.5);
  doc.setTextColor(118, 133, 127);
  doc.text(signatory?.designation || "Authorised signatory", margin, blockTop + 73);
  doc.text(`For ${APP.org}`, margin, blockTop + 86);

  doc.setDrawColor(200, 210, 205);
  doc.rect(width - margin - 150, blockTop, 150, 86);
  doc.setTextColor(170, 180, 175);
  doc.text("Stamp", width - margin - 85, blockTop + 48);

  // ---- cancelled overlay ----
  if (String(certificate.Status || "").toLowerCase() === "cancelled") {
    doc.saveGraphicsState();
    if (doc.setGState) doc.setGState(new doc.GState({ opacity: 0.18 }));
    doc.setFont("helvetica", "bold");
    doc.setFontSize(76);
    doc.setTextColor(194, 59, 59);
    doc.text("CANCELLED", width / 2, height / 2, { align: "center", angle: 32 });
    doc.restoreGraphicsState();
  }

  return doc;
}

/** The logo is optional — a missing or blocked image must not stop the PDF. */
async function loadLogo(url) {
  if (!url) return null;
  try {
    const response = await fetch(url, { mode: "cors" });
    if (!response.ok) return null;
    const blob = await response.blob();
    return await new Promise((resolve) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}
